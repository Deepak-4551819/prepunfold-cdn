import re

def refine_hindi(text):
    if not text:
        return ""
    s = text

    subs = [
        ("Sce. åJeeruej", "एम. व्हीलर"),
        ("åJeeruej", "व्हीलर"),
        ("बैनजाa", "बनर्जी"),
        ("कानिËघम", "कनिंघम"),
        ("कनिËघम", "कनिंघम"),
        ("बQटिक", "बैंटिक"),
        ("नियुक्यत", "नियुक्त"),
        ("समüट", "सम्राट"),
        ("मõस", "मद्रास"),
        ("परवरी", "फरवरी"),
        ("किसन", "किसान"),
        ("इतिहस", "इतिहास"),
        ("सह्यता", "सहायता"),
        ("हेने", "होने"),
        ("हेकर", "होकर"),
        ("आथिक", "आर्थिक"),
        ("शŒाrकरण", "शस्त्रीकरण"),
        ("क्QबिÇज", "कैम्ब्रिज"),
        ("अक्यट्ूबर", "अक्टूबर"),
        ("फिक्यकी", "फिक्की"),
        ("टट आयरन", "टाटा आयरन"),
        ("क्ंपनी", "कम्पनी"),
        ("साfम्मलित", "सम्मिलित"),
        ("अंगुली छ", "अंगुली छाप"),
        ("मुत्ति", "मुक्ति"),
        ("वीfह्नी", "वाहिनी"),
        ("संयुत्त", "संयुक्त"),
        ("गाfठत", "गठित"),
        ("एट्लांfट्क", "अटलांटिक"),
        ("चार्ट्र", "चार्टर"),
        ("नेfट्व", "नेटिव"),
        ("अबा@जाaनेस", "एबोरिजिनल्स"),
        ("द्ेंग शियाओ पिंग", "देंग शियाओपिंग"),
        ("कार्ल माक्यर्स", "कार्ल मार्क्स"),
        ("øोडरिक एंगेल्स", "फ्रेडरिक एंगेल्स"),
        ("मैनिपेस्टे", "मैनिफेस्टो"),
        ("झ्र", "प्री"),
        ("घ्ह्dग्aह", "इतिहास"),
        ("एज्त.", "विशेष"),
        ("अध्यास्थ.", "अध्ययन"),
        ("बैंटिक", "बेंटिक"),
        ("लॉर्डज कर्जन", "लॉर्ड कर्जन"),
    ]
    for k, v in subs:
        s = s.replace(k, v)

    # Clean legacy font markers
    s = s.replace("Ë", "ं")
    s = s.replace("ü", "्रा")
    s = s.replace("õ", "द्र")
    s = s.replace("Ç", "्र")
    s = s.replace("Œ", "स्त्र")
    s = s.replace("Q", "ै")
    s = s.replace("Š", " :")
    s = s.replace("a", "ी")

    # Double halant / broken conjuncts
    s = s.replace("्d", "्")
    s = s.replace("क्यत", "क्त")
    s = s.replace("ीि", "ी")
    s = s.replace("िी", "ी")
    s = s.replace("ाे", "ो")
    s = s.replace("ाै", "ौ")

    return s.strip()

samples = [
    "Sce. åJeeruej",
    "आर.डी. बैनजाa",
    "ए. कानिËघम",
    "लॉर्ड बQटिक",
    "नियुक्यत",
    "समüट लुई",
    "मõस श्रमिक संघ",
    "कार्ल माक्यर्स व øोडरिक एंगेल्स",
    "क्QबिÇज इतिहस"
]

for sample in samples:
    print(f"{sample:<35} -> {refine_hindi(sample)}")
