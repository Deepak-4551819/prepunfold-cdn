def clean_hindi_text(text):
    if not text:
        return ""
    s = str(text)
    for k, v in HINDI_REPLACEMENTS:
        s = s.replace(k, v)
    # Cleanup leftover stray symbols
    s = s.replace('å', 'ह्व').replace('ä', '').replace('°', '.').replace('@', '').replace('^', '').replace('§', '')
    return s
