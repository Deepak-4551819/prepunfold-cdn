def get_physics_2m_questions(test_num):
    tid = f"gate_ph_mock_{test_num:02d}"
    tag = f"GATE PH Full Mock {test_num:02d}"
    qs = []

    # 1. 15 MCQs (Q36 to Q50)
    for qnum in range(36, 51):
        qid = f"{tid}_q{qnum:03d}"
        q_obj = generate_ph_2m_mcq(test_num, qnum, qid, tag)
        qs.append(q_obj)

    # 2. 5 MSQs (Q51 to Q55)
    for qnum in range(51, 56):
        qid = f"{tid}_q{qnum:03d}"
        q_obj = generate_ph_2m_msq(test_num, qnum, qid, tag)
        qs.append(q_obj)

    # 3. 10 NATs (Q56 to Q65)
    for qnum in range(56, 66):
        qid = f"{tid}_q{qnum:03d}"
        q_obj = generate_ph_2m_nat(test_num, qnum, qid, tag)
        qs.append(q_obj)

    return qs

