# -*- coding: utf-8 -*-
import json, re

def clean_hindi_text(text):
    if not text:
        return ""
    s = text

    # Direct string repairs of common multi-char corrupted tokens
    direct_replacements = [
        ('त्र+ग्वैfद्क', 'ऋग्वैदिक'),
        ('त्र+ग्वेद्', 'ऋग्वेद'),
        ('त्र+', 'ऋ'),
        ('आयाX', 'आर्यों'),
        ('याX', 'र्यों'),
        ('X', 'र्यों'),
        ('ह्Ìडप्पा', 'हड़प्पा'),
        ('ह्Ìड', 'हड़'),
        ('Ìढr', 'ढ़ी'),
        ('Ìढ', 'ढ़'),
        ('Ìडें', 'ड़ों'),
        ('Ìड', 'ड़'),
        ('Ì', 'ड़'),
        ('सिæन्त', 'सिद्धान्त'),
        ('प्रसिæ', 'प्रसिद्ध'),
        ('æ', 'द्ध'),
        ('उÅोतन', 'उद्योतन'),
        ('Å', 'द्य'),
        ('ह्रिभõ', 'हरिभद्र'),
        ('गुणचन्õ', 'गुणचन्द्र'),
        ('समुõ', 'समुद्र'),
        ('õ', 'द्र'),
        ('बि°', 'बिष्ट'),
        ('°', 'ष्ट'),
        ('आ|थक', 'आर्थिक'),
        ('|', 'र्'),
        ('राष्ट्^पति', 'राष्ट्रपति'),
        ('अन्तराष्ट्^ीय', 'अन्तर्राष्ट्रीय'),
        ('अन्तर्राष्ट्^ीय', 'अन्तर्राष्ट्रीय'),
        ('^', ''),
        ('गिल›िस्ट्', 'गिलक्राइस्ट'),
        ('परि›मा', 'परिक्रमा'),
        ('›', 'क्र'),
        ('राजनीतिशाŒ', 'राजनीतिशास्त्र'),
        ('शाŒ', 'शास्त्र'),
        ('Œ', 'स्त्र'),
        ('चट्dटन', 'चट्टान'),
        ('ट्dट', 'ट्ट'),
        ('ट्d', 'ट्ट'),
        ('dट', 'ट्ट'),
        ('धÇुवीय', 'ध्रुवीय'),
        ('Çु', '्रु'),
        ('Ç', '्र'),
        ('Tपर', 'ऊपर'),
        ('Tप', 'ऊप'),
        ('T', 'ऊ'),
        ('क््रषि', 'कृषि'),
        ('क््र', 'कृ'),
        ('आ£न', 'आह्वान'),
        ('£', ''),
        ('अ®ण', 'अरुण'),
        ('®प', 'रूप'),
        ('®', 'रु'),
        ('सQधव', 'सैन्धव'),
        ('Q', 'ैं'),
        ('™प', 'रूप'),
        ('™', 'रू'),
        ('«ोनाइट्', 'ग्रेनाइट'),
        ('«ोनाइट', 'ग्रेनाइट'),
        ('«ाम', 'ग्राम'),
        ('«ंथ', 'ग्रंथ'),
        ('«न्थ', 'ग्रंथ'),
        ('«', 'ग्र'),
        ('नहR', 'नहीं'),
        ('नहr', 'नहीं'),
        ('R', 'ीं'),
        ('कार्यवाहr', 'कार्रवाई'),
        ('कार्यवाही', 'कार्रवाई'),
        ('चीfह्ए', 'चाहिए'),
        ('व्यवहरवाद्', 'व्यवहारवाद'),
        ('व्यवहर', 'व्यवहार'),
        ('आन्देलन', 'आंदोलन'),
        ('अह्मदबाद्', 'अहमदाबाद'),
        ('अहमदबाद्', 'अहमदाबाद'),
        ('मोह्नजोद्Ìडें', 'मोहनजोदड़ो'),
        ('मोह्नजो', 'मोहनजो'),
        ('ड@.', 'डॉ.'),
        ('fह्सार', 'हिसार'),
        ('ह्रियाणा', 'हरियाणा'),
        ('fह्रण्यस्तूप', 'हिरण्यस्तूप'),
        ('fद्व्यावदन', 'दिव्यावदान'),
        ('गविfष्ठ', 'गविष्टि'),
        ('दrघ', 'दीर्घ'),
        ('नदr', 'नदी'),
        ('टrला', 'टीला'),
        ('हr', 'ही'),
        ('दr', 'दी'),
        ('क्यया', 'क्या'),
        ('ºण्', '°C'),
        ('º', '°')
    ]
    for k, v in direct_replacements:
        s = s.replace(k, v)

    # Short-i repair: 'f' followed by Hindi consonant (or conjunct)
    # e.g., fद्शा -> दिशा, fद्न -> दिन, fड -> डि, fक -> कि
    def fix_f(m):
        char = m.group(1)
        return char + 'ि'
    s = re.sub(r'f([क-ह])', fix_f, s)

    # Word-level fixes
    # कह -> कहा
    s = re.sub(r'\bकह(?=\s+(?:जाता|गया|था|है|हो|गई|थे))\b', 'कहा', s)
    s = re.sub(r'\b(?:ने|द्वारा)\s+कह\b', lambda m: m.group(0)[:-2] + 'कहा', s)
    s = re.sub(r'\bकिसने कह\b', 'किसने कहा', s)

    # दे -> दो (when meaning two)
    s = re.sub(r'\bदे(?=\s+(?:मुख्य|नारे|मील|प्रकार|भाग|रूप|वर्ष|दिन|महीने|स्तंभ|चरण|वर्ग|प्रवृत्तियां|बातों|दलों))\b', 'दो', s)

    # हेता, हेती, हेते, हेना, हेने -> होता, होती, होते, होना, होने
    s = re.sub(r'\bहेता\b', 'होता', s)
    s = re.sub(r'\bहेती\b', 'होती', s)
    s = re.sub(r'\bहेते\b', 'होते', s)
    s = re.sub(r'\bहेना\b', 'होना', s)
    s = re.sub(r'\bहेने\b', 'होने', s)
    s = re.sub(r'\bह्म\b', 'हम', s)

    # Fix ह् followed by matras: ह्ो -> हो, ह्ै -> है, ह्ु -> हु, ह्ू -> हू, ह्ी -> ही, ह्ा -> हा
    s = re.sub(r'ह्([ािीुूेैोौंँ])', r'ह\1', s)

    # Fix द् followed by e/ai matra: द्े -> दे, द्ै -> दै, द्ा -> दा, द्ी -> दी, द्ु -> दु
    s = re.sub(r'द्([ािीुूेैोौंँ])', r'द\1', s)

    # Fix ह् at end of words: यह् -> यह, वह् -> वह, समूह् -> समूह, स्नानगृह् -> स्नानगृह, बारह् -> बारह, चारागाह् -> चारागाह, तरह् -> तरह, विद््रोह् -> विद्रोह
    s = re.sub(r'([क-ह])ह्\b', r'\1ह', s)

    # Fix ह् in common positions: उन्ह्ें -> उन्हें, इन्ह्ें -> इन्हें, किन्ह्ें -> किन्हें, मह्त्व -> महत्व, रह्ते -> रहते, रह्कर -> रहकर
    s = s.replace('उन्ह्ें', 'उन्हें').replace('इन्ह्ें', 'न्हें').replace('मह्त्व', 'महत्व').replace('रह्ते', 'रहते').replace('रह्कर', 'रहकर').replace('रह्ने', 'रहने').replace('रह्ता', 'रहता').replace('रह्ती', 'रहती')
    s = s.replace('ह्स्ताक्षर', 'हस्ताक्षर').replace('ह्त्या', 'हत्या')

    # Plural endings like Gayaaen, Manusyaen: ाें -> ों, आें -> ओं
    s = re.sub(r'([क-ह])ाें\b', r'\1ों', s)
    s = re.sub(r'([क-ह])ाें(?=[\s\,\.\?\!\:\;])', r'\1ों', s)
    s = re.sub(r'आें\b', 'ओं', s)
    s = re.sub(r'आें(?=[\s\,\.\?\!\:\;])', 'ओं', s)

    # Fix unnecessary trailing halants on full words (e.g. सेट् -> सेट, बाद् -> बाद, शब्द् -> शब्द, पिट्क -> पिटक)
    s = re.sub(r'([क-ह])्\b', r'\1', s)

    # Specific common fixes
    s = s.replace('शत्ति', 'शक्ति').replace('व्यत्ति', 'व्यक्ति').replace('सन्द्र्भ', 'सन्दर्भ')
    s = s.replace('स्थयी', 'स्थायी').replace('अस्थई', 'अस्थायी')
    s = s.replace('क्ुछ', 'कुछ').replace('क्ुल', 'कुल').replace('क्ुनाल', 'कुणाल')
    s = s.replace('हवाआ', 'हवाओं').replace('रेखाआ', 'रेखाओं')
    s = s.replace('वायुदब', 'वायुदाब').replace('समदब', 'समदाब')

    return s

if __name__ == '__main__':
    with open('tests/teaching/tgt_pgt_civics/pyq/tgt_pgt_civics_pyq_up_tgt_2021.json', 'r', encoding='utf-8') as f:
        d = json.load(f)

    for i in range(5):
        q = d['questions'][i]
        print(f'=== Q{i+1} CLEANED ===')
        print('QTextHi:', clean_hindi_text(q['questionTextHi']))
        print('OptsHi:', [clean_hindi_text(o) for o in q['optionsHi']])
        print('ExpHi:', clean_hindi_text(q['explanationHi'])[:160])
